-- Inventory reconciliation repair registry and approval lifecycle (stage 2B).
-- This migration deliberately creates no business-data executor: products,
-- inventory movements and journal entries remain read-only to this workflow.

CREATE TABLE public.inventory_reconciliation_repairs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  repair_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'ready_for_review', 'approved', 'executed', 'cancelled', 'reversed')),
  title text NOT NULL CHECK (btrim(title) <> ''),
  explanation text NOT NULL CHECK (btrim(explanation) <> ''),
  diagnostic_fingerprint text NOT NULL CHECK (btrim(diagnostic_fingerprint) <> ''),
  diagnostic_snapshot_at timestamptz NOT NULL,
  source_scope text NOT NULL CHECK (source_scope = 'all_recorded_stock_effects'),
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  accounting_date date,
  reverses_repair_id uuid REFERENCES public.inventory_reconciliation_repairs(id),
  reversed_by_repair_id uuid REFERENCES public.inventory_reconciliation_repairs(id),
  separation_override_reason text,
  prepared_by uuid NOT NULL REFERENCES auth.users(id),
  prepared_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  submitted_by uuid REFERENCES auth.users(id),
  submitted_at timestamptz,
  approved_by uuid REFERENCES auth.users(id),
  approved_at timestamptz,
  executed_by uuid REFERENCES auth.users(id),
  executed_at timestamptz,
  cancelled_by uuid REFERENCES auth.users(id),
  cancelled_at timestamptz,
  cancellation_reason text,
  reversed_by uuid REFERENCES auth.users(id),
  reversed_at timestamptz,
  reversal_reason text,
  created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  CHECK (reverses_repair_id IS NULL OR reverses_repair_id <> id),
  CHECK (reversed_by_repair_id IS NULL OR reversed_by_repair_id <> id),
  CHECK ((status <> 'ready_for_review') OR (submitted_by IS NOT NULL AND submitted_at IS NOT NULL)),
  CHECK ((status <> 'approved') OR (submitted_by IS NOT NULL AND submitted_at IS NOT NULL
    AND approved_by IS NOT NULL AND approved_at IS NOT NULL)),
  CHECK ((status <> 'executed') OR (approved_by IS NOT NULL AND approved_at IS NOT NULL
    AND executed_by IS NOT NULL AND executed_at IS NOT NULL)),
  CHECK ((status <> 'cancelled') OR (cancelled_by IS NOT NULL AND cancelled_at IS NOT NULL
    AND NULLIF(btrim(cancellation_reason), '') IS NOT NULL)),
  CHECK ((status <> 'reversed') OR (reversed_by IS NOT NULL AND reversed_at IS NOT NULL
    AND NULLIF(btrim(reversal_reason), '') IS NOT NULL))
);

CREATE TABLE public.inventory_reconciliation_repair_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  repair_id uuid NOT NULL REFERENCES public.inventory_reconciliation_repairs(id),
  line_number integer NOT NULL CHECK (line_number > 0),
  axis text NOT NULL CHECK (axis IN ('product', 'source')),
  issue_key text NOT NULL CHECK (btrim(issue_key) <> ''),
  classification text NOT NULL CHECK (classification IN (
    'product_balance', 'movement_without_journal', 'journal_without_movement',
    'undocumented_effect', 'rounding'
  )),
  repair_type text NOT NULL CHECK (repair_type IN (
    'rebuild_product_card', 'create_missing_inventory_journal',
    'reverse_unbacked_inventory_journal', 'create_linked_inventory_adjustment',
    'post_rounding_adjustment', 'manual_review'
  )),
  product_id uuid REFERENCES public.products(id),
  source_type text,
  source_id uuid,
  source_number text,
  original_journal_entry_id uuid REFERENCES public.journal_entries(id),
  before_card_quantity numeric,
  before_movement_quantity numeric,
  before_movement_book_value numeric(18,2),
  before_ledger_1104_value numeric(18,2),
  proposed_card_quantity numeric,
  proposed_movement_book_value numeric(18,2),
  proposed_ledger_1104_value numeric(18,2),
  after_card_quantity numeric,
  after_movement_quantity numeric,
  after_movement_book_value numeric(18,2),
  after_ledger_1104_value numeric(18,2),
  before_state jsonb NOT NULL CHECK (jsonb_typeof(before_state) = 'object'),
  proposed_state jsonb NOT NULL CHECK (jsonb_typeof(proposed_state) = 'object'),
  after_state jsonb CHECK (after_state IS NULL OR jsonb_typeof(after_state) = 'object'),
  precondition_hash text NOT NULL CHECK (btrim(precondition_hash) <> ''),
  result_status text NOT NULL DEFAULT 'pending'
    CHECK (result_status IN ('pending', 'applied', 'failed', 'skipped')),
  result_message text,
  created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  UNIQUE (repair_id, line_number),
  UNIQUE (repair_id, axis, issue_key),
  CHECK (
    (axis = 'product' AND product_id IS NOT NULL AND source_id IS NULL)
    OR (axis = 'source' AND product_id IS NULL AND source_type IS NOT NULL AND source_id IS NOT NULL)
  )
);

CREATE TABLE public.inventory_reconciliation_repair_effects (
