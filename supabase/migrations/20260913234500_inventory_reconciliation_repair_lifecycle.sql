CREATE FUNCTION public.inventory_reconciliation_repair_require_actor(
  p_admin_only boolean DEFAULT false
)
RETURNS uuid
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
DECLARE
  v_actor uuid := auth.uid();
  v_is_admin boolean;
  v_is_accountant boolean;
BEGIN
  IF v_actor IS NULL THEN
    RAISE EXCEPTION 'REPAIR_ACCESS_DENIED' USING ERRCODE = '42501';
  END IF;

  v_is_admin := public.has_role(v_actor, 'admin'::public.app_role);
  v_is_accountant := public.has_role(v_actor, 'accountant'::public.app_role);
  IF (p_admin_only AND NOT v_is_admin)
     OR (NOT p_admin_only AND NOT (v_is_admin OR v_is_accountant)) THEN
    RAISE EXCEPTION 'REPAIR_ACCESS_DENIED' USING ERRCODE = '42501';
  END IF;
  RETURN v_actor;
END;
$function$;

CREATE FUNCTION public.inventory_reconciliation_repair_result(p_repair_id uuid)
RETURNS jsonb
