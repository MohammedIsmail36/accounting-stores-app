CREATE FUNCTION public.inventory_reconciliation_repair_replay(
  p_request_id uuid,
  p_event_type text,
  p_actor_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
DECLARE v_event public.inventory_reconciliation_repair_events%ROWTYPE;
BEGIN
  SELECT * INTO v_event
  FROM public.inventory_reconciliation_repair_events
  WHERE request_id = p_request_id;

  IF NOT FOUND THEN
    RETURN NULL;
  END IF;
  IF v_event.event_type IS DISTINCT FROM p_event_type
     OR v_event.actor_id IS DISTINCT FROM p_actor_id THEN
    RAISE EXCEPTION 'REPAIR_REQUEST_CONFLICT' USING ERRCODE = '23505';
  END IF;
  RETURN v_event.event_data->'result';
END;
$function$;

CREATE FUNCTION public.inventory_reconciliation_replace_repair_items(
  p_repair_id uuid,
  p_items jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
DECLARE
  v_item jsonb;
  v_row jsonb;
  v_diagnostic jsonb;
  v_axis text;
  v_issue_key text;
  v_classification text;
  v_repair_type text;
  v_product_id uuid;
  v_source_id uuid;
  v_source_type text;
  v_search text;
  v_line integer := 0;
  v_proposed_state jsonb;
  v_precondition_hash text;
BEGIN
  IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array'
     OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'REPAIR_ITEMS_REQUIRED' USING ERRCODE = '22023';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_array_elements(p_items) x
    GROUP BY lower(btrim(x->>'axis')), btrim(x->>'issue_key')
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'REPAIR_DUPLICATE_ISSUE' USING ERRCODE = '22023';
  END IF;

  -- A deterministic lock order prevents two concurrent drafts from claiming
  -- the same issue and avoids lock-order deadlocks for multi-item repairs.
  FOR v_axis, v_issue_key IN
    SELECT lower(btrim(x->>'axis')), btrim(x->>'issue_key')
    FROM jsonb_array_elements(p_items) x
    ORDER BY 1, 2
  LOOP
    IF v_axis NOT IN ('product', 'source') OR NULLIF(v_issue_key, '') IS NULL THEN
      RAISE EXCEPTION 'REPAIR_INVALID_ISSUE' USING ERRCODE = '22023';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended('inventory-repair:' || v_axis || ':' || v_issue_key, 0));
    IF EXISTS (
      SELECT 1
      FROM public.inventory_reconciliation_repair_items i
      JOIN public.inventory_reconciliation_repairs r ON r.id = i.repair_id
      WHERE i.axis = v_axis
        AND i.issue_key = v_issue_key
        AND i.repair_id <> p_repair_id
        AND r.status IN ('draft', 'ready_for_review', 'approved')
    ) THEN
      RAISE EXCEPTION 'REPAIR_ISSUE_ACTIVE' USING ERRCODE = '55000';
    END IF;
  END LOOP;

  DELETE FROM public.inventory_reconciliation_repair_items WHERE repair_id = p_repair_id;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_items)
  LOOP
    v_line := v_line + 1;
    v_axis := lower(btrim(v_item->>'axis'));
    v_issue_key := btrim(v_item->>'issue_key');
    v_classification := btrim(v_item->>'classification');
    v_repair_type := btrim(v_item->>'repair_type');
    v_row := NULL;

    IF v_axis = 'product' THEN
      BEGIN
        v_product_id := (v_item->>'product_id')::uuid;
      EXCEPTION WHEN invalid_text_representation THEN
        RAISE EXCEPTION 'REPAIR_SOURCE_NOT_FOUND' USING ERRCODE = '22023';
      END;
      SELECT p.code INTO v_search FROM public.products p WHERE p.id = v_product_id;
      IF v_search IS NULL THEN
        RAISE EXCEPTION 'REPAIR_SOURCE_NOT_FOUND' USING ERRCODE = '22023';
      END IF;
      v_diagnostic := public.get_inventory_reconciliation_diagnostic(
        'products', true, v_search, 500, 0, NULL);
      SELECT value INTO v_row
      FROM jsonb_array_elements(v_diagnostic->'rows')
      WHERE value->>'product_id' = v_product_id::text
      LIMIT 1;
      IF v_row IS NULL OR v_row->>'classification' = 'matched' THEN
        RAISE EXCEPTION 'REPAIR_ISSUE_NOT_FOUND' USING ERRCODE = '22023';
      END IF;
      IF v_issue_key IS DISTINCT FROM 'product:' || v_product_id::text THEN
        RAISE EXCEPTION 'REPAIR_ISSUE_KEY_MISMATCH' USING ERRCODE = '22023';
      END IF;
      IF v_classification IS DISTINCT FROM v_row->>'classification' THEN
        RAISE EXCEPTION 'REPAIR_CLASSIFICATION_CHANGED' USING ERRCODE = '40001';
      END IF;
      IF v_repair_type = 'rebuild_product_card' THEN
        IF v_classification <> 'product_balance'
           OR COALESCE((v_row->>'can_prepare_repair')::boolean, false) IS NOT TRUE THEN
          RAISE EXCEPTION 'REPAIR_TYPE_INVALID_FOR_ISSUE' USING ERRCODE = '22023';
        END IF;
        v_proposed_state := jsonb_build_object(
          'card_quantity', (v_row->>'movement_quantity')::numeric
        );
      ELSIF v_repair_type = 'create_linked_inventory_adjustment' THEN
        v_proposed_state := COALESCE(v_item->'proposed_state', '{}'::jsonb);
      ELSIF v_repair_type = 'manual_review' THEN
        v_proposed_state := COALESCE(v_item->'proposed_state', '{}'::jsonb);
      ELSE
        RAISE EXCEPTION 'REPAIR_TYPE_INVALID_FOR_ISSUE' USING ERRCODE = '22023';
      END IF;

      v_precondition_hash := md5(jsonb_build_object(
        'axis', v_axis, 'issue_key', v_issue_key, 'diagnostic', v_row,
        'repair_type', v_repair_type, 'proposed_state', v_proposed_state
      )::text);

      INSERT INTO public.inventory_reconciliation_repair_items (
        repair_id, line_number, axis, issue_key, classification, repair_type,
        product_id, before_card_quantity, before_movement_quantity,
        before_movement_book_value, proposed_card_quantity, before_state,
        proposed_state, precondition_hash
      ) VALUES (
        p_repair_id, v_line, v_axis, v_issue_key, v_classification, v_repair_type,
        v_product_id, (v_row->>'card_quantity')::numeric,
        (v_row->>'movement_quantity')::numeric,
        (v_row->>'movement_book_value')::numeric,
        CASE WHEN v_proposed_state ? 'card_quantity'
          THEN (v_proposed_state->>'card_quantity')::numeric END,
        v_row, v_proposed_state, v_precondition_hash
      );
    ELSE
      v_source_type := btrim(v_item->>'source_type');
      BEGIN
        v_source_id := (v_item->>'source_id')::uuid;
      EXCEPTION WHEN invalid_text_representation THEN
        RAISE EXCEPTION 'REPAIR_SOURCE_NOT_FOUND' USING ERRCODE = '22023';
      END;
      IF NULLIF(v_source_type, '') IS NULL OR v_source_id IS NULL THEN
        RAISE EXCEPTION 'REPAIR_SOURCE_NOT_FOUND' USING ERRCODE = '22023';
      END IF;
      v_diagnostic := public.get_inventory_reconciliation_diagnostic(
        'sources', true, v_source_id::text, 500, 0, NULL);
      SELECT value INTO v_row
      FROM jsonb_array_elements(v_diagnostic->'rows')
      WHERE value->>'source_id' = v_source_id::text
        AND value->>'source_type' = v_source_type
      LIMIT 1;
      IF v_row IS NULL OR v_row->>'classification' = 'matched' THEN
        RAISE EXCEPTION 'REPAIR_SOURCE_NOT_FOUND' USING ERRCODE = '22023';
      END IF;
      IF v_issue_key IS DISTINCT FROM v_row->>'source_key' THEN
        RAISE EXCEPTION 'REPAIR_ISSUE_KEY_MISMATCH' USING ERRCODE = '22023';
      END IF;
      IF v_classification IS DISTINCT FROM v_row->>'classification' THEN
        RAISE EXCEPTION 'REPAIR_CLASSIFICATION_CHANGED' USING ERRCODE = '40001';
      END IF;
      IF NOT (
        (v_classification = 'movement_without_journal' AND v_repair_type = 'create_missing_inventory_journal')
        OR (v_classification = 'journal_without_movement' AND v_repair_type = 'reverse_unbacked_inventory_journal')
        OR (v_classification = 'rounding' AND v_repair_type = 'post_rounding_adjustment')
        OR (v_classification = 'undocumented_effect' AND v_repair_type IN ('create_linked_inventory_adjustment', 'manual_review'))
      ) THEN
        RAISE EXCEPTION 'REPAIR_TYPE_INVALID_FOR_ISSUE' USING ERRCODE = '22023';
      END IF;
      v_proposed_state := COALESCE(v_item->'proposed_state', '{}'::jsonb);
      v_precondition_hash := md5(jsonb_build_object(
        'axis', v_axis, 'issue_key', v_issue_key, 'diagnostic', v_row,
        'repair_type', v_repair_type, 'proposed_state', v_proposed_state
      )::text);

      INSERT INTO public.inventory_reconciliation_repair_items (
        repair_id, line_number, axis, issue_key, classification, repair_type,
        source_type, source_id, source_number, original_journal_entry_id,
        before_movement_quantity, before_movement_book_value,
        before_ledger_1104_value, proposed_movement_book_value,
        proposed_ledger_1104_value, before_state, proposed_state,
        precondition_hash
      ) VALUES (
        p_repair_id, v_line, v_axis, v_issue_key, v_classification, v_repair_type,
        v_source_type, v_source_id, v_row->>'source_number',
        NULLIF(v_row->>'journal_entry_id', '')::uuid,
        NULLIF(v_row->>'movement_quantity', '')::numeric,
        NULLIF(v_row->>'movement_book_value', '')::numeric,
        NULLIF(v_row->>'ledger_1104_value', '')::numeric,
        NULLIF(v_item->>'proposed_movement_book_value', '')::numeric,
        NULLIF(v_item->>'proposed_ledger_1104_value', '')::numeric,
        v_row, v_proposed_state, v_precondition_hash
      );
    END IF;
  END LOOP;
END;
$function$;

CREATE FUNCTION public.create_inventory_reconciliation_repair(
  p_title text,
  p_explanation text,
  p_diagnostic_fingerprint text,
  p_diagnostic_snapshot_at timestamptz,
  p_source_scope text,
  p_items jsonb,
  p_request_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
DECLARE v_actor uuid; v_repair_id uuid; v_result jsonb; v_replay jsonb;
BEGIN
  v_actor := public.inventory_reconciliation_repair_require_actor(false);
  IF p_request_id IS NULL THEN
    RAISE EXCEPTION 'REPAIR_REQUEST_ID_REQUIRED' USING ERRCODE = '22023';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('inventory-repair-request:' || p_request_id::text, 0));
  v_replay := public.inventory_reconciliation_repair_replay(p_request_id, 'created', v_actor);
  IF v_replay IS NOT NULL THEN RETURN v_replay; END IF;

  IF NULLIF(btrim(COALESCE(p_title, '')), '') IS NULL
     OR NULLIF(btrim(COALESCE(p_explanation, '')), '') IS NULL
     OR NULLIF(btrim(COALESCE(p_diagnostic_fingerprint, '')), '') IS NULL
     OR p_diagnostic_snapshot_at IS NULL
     OR p_source_scope IS DISTINCT FROM 'all_recorded_stock_effects' THEN
    RAISE EXCEPTION 'REPAIR_INVALID_HEADER' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.inventory_reconciliation_repairs (
    title, explanation, diagnostic_fingerprint, diagnostic_snapshot_at,
    source_scope, prepared_by
  ) VALUES (
    btrim(p_title), btrim(p_explanation), btrim(p_diagnostic_fingerprint),
    p_diagnostic_snapshot_at, p_source_scope, v_actor
  ) RETURNING id INTO v_repair_id;

  PERFORM public.inventory_reconciliation_replace_repair_items(v_repair_id, p_items);
  v_result := public.inventory_reconciliation_repair_result(v_repair_id);
  INSERT INTO public.inventory_reconciliation_repair_events (
    repair_id, event_type, from_status, to_status, request_id, actor_id, event_data
  ) VALUES (
    v_repair_id, 'created', NULL, 'draft', p_request_id, v_actor,
    jsonb_build_object('result', v_result)
  );
  RETURN v_result;
END;
$function$;

CREATE FUNCTION public.update_inventory_reconciliation_repair(
  p_id uuid,
  p_title text,
  p_explanation text,
  p_items jsonb,
  p_expected_version integer,
  p_request_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
DECLARE v_actor uuid; v_repair public.inventory_reconciliation_repairs%ROWTYPE; v_result jsonb; v_replay jsonb;
BEGIN
  v_actor := public.inventory_reconciliation_repair_require_actor(false);
  IF p_request_id IS NULL THEN RAISE EXCEPTION 'REPAIR_REQUEST_ID_REQUIRED' USING ERRCODE = '22023'; END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('inventory-repair-request:' || p_request_id::text, 0));
  v_replay := public.inventory_reconciliation_repair_replay(p_request_id, 'updated', v_actor);
  IF v_replay IS NOT NULL THEN RETURN v_replay; END IF;

  SELECT * INTO v_repair FROM public.inventory_reconciliation_repairs WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'REPAIR_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
  IF v_repair.status <> 'draft' THEN RAISE EXCEPTION 'REPAIR_STATUS_INVALID' USING ERRCODE = '55000'; END IF;
  IF v_repair.version IS DISTINCT FROM p_expected_version THEN
    RAISE EXCEPTION 'REPAIR_VERSION_CONFLICT' USING ERRCODE = '40001';
  END IF;
  IF NULLIF(btrim(COALESCE(p_title, '')), '') IS NULL
     OR NULLIF(btrim(COALESCE(p_explanation, '')), '') IS NULL THEN
    RAISE EXCEPTION 'REPAIR_INVALID_HEADER' USING ERRCODE = '22023';
  END IF;

  PERFORM public.inventory_reconciliation_replace_repair_items(p_id, p_items);
  UPDATE public.inventory_reconciliation_repairs
  SET title = btrim(p_title), explanation = btrim(p_explanation),
      version = version + 1, updated_at = statement_timestamp()
  WHERE id = p_id;
  v_result := public.inventory_reconciliation_repair_result(p_id);
  INSERT INTO public.inventory_reconciliation_repair_events (
    repair_id, event_type, from_status, to_status, request_id, actor_id, event_data
  ) VALUES (p_id, 'updated', 'draft', 'draft', p_request_id, v_actor, jsonb_build_object('result', v_result));
  RETURN v_result;
END;
$function$;

