CREATE FUNCTION public.cancel_inventory_reconciliation_repair(
  p_id uuid,
  p_reason text,
  p_expected_version integer,
  p_request_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $function$
DECLARE v_actor uuid; v_repair public.inventory_reconciliation_repairs%ROWTYPE; v_result jsonb; v_replay jsonb;
BEGIN
  v_actor := public.inventory_reconciliation_repair_require_actor(false);
  IF p_request_id IS NULL THEN RAISE EXCEPTION 'REPAIR_REQUEST_ID_REQUIRED' USING ERRCODE = '22023'; END IF;
  IF NULLIF(btrim(COALESCE(p_reason, '')), '') IS NULL THEN
    RAISE EXCEPTION 'REPAIR_CANCELLATION_REASON_REQUIRED' USING ERRCODE = '22023';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('inventory-repair-request:' || p_request_id::text, 0));
  v_replay := public.inventory_reconciliation_repair_replay(p_request_id, 'cancelled', v_actor);
  IF v_replay IS NOT NULL THEN RETURN v_replay; END IF;
  SELECT * INTO v_repair FROM public.inventory_reconciliation_repairs WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'REPAIR_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
  IF v_repair.status NOT IN ('draft', 'ready_for_review', 'approved') THEN
    RAISE EXCEPTION 'REPAIR_STATUS_INVALID' USING ERRCODE = '55000';
  END IF;
  IF v_repair.status = 'approved'
     AND NOT public.has_role(v_actor, 'admin'::public.app_role) THEN
    RAISE EXCEPTION 'REPAIR_ACCESS_DENIED' USING ERRCODE = '42501';
  END IF;
  IF v_repair.version IS DISTINCT FROM p_expected_version THEN
    RAISE EXCEPTION 'REPAIR_VERSION_CONFLICT' USING ERRCODE = '40001';
  END IF;
  UPDATE public.inventory_reconciliation_repairs
  SET status = 'cancelled', cancelled_by = v_actor, cancelled_at = statement_timestamp(),
      cancellation_reason = btrim(p_reason), version = version + 1,
      updated_at = statement_timestamp()
  WHERE id = p_id;
  v_result := public.inventory_reconciliation_repair_result(p_id);
  INSERT INTO public.inventory_reconciliation_repair_events (
    repair_id, event_type, from_status, to_status, request_id, actor_id, event_data
  ) VALUES (p_id, 'cancelled', v_repair.status, 'cancelled', p_request_id, v_actor,
    jsonb_build_object('result', v_result, 'reason', btrim(p_reason)));
  RETURN v_result;
END;
$function$;

